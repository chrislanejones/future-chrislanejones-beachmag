"""Copy the design's CSS out of the built homepage into site/ so the Next.js skin matches it.

Run after `pnpm run build`. Keeps every <style> block in page order, drops the Google Fonts
@imports (site/ loads Bodoni Moda and DM Sans through next/font) and points the font names at
the next/font variables.
"""
import re
from pathlib import Path

page = Path('outputs/coastal-homepage.html').read_text(encoding='utf-8')
blocks = re.findall(r'<style[^>]*>(.*?)</style>', page, re.S)
# The first block is the preview wrapper (body background, 1240px column); site/ has its own.
assert blocks[0].lstrip().startswith('body{margin:0;background:#172f32}'), 'Preview wrapper block moved'


def site_css(css, source, out):
    css = re.sub(r"@import url\('https://fonts\.googleapis\.com/[^)]*\);?", '', css)
    css = css.replace("'Bodoni Moda'", 'var(--font-bodoni-moda)').replace("'DM Sans'", 'var(--font-dm-sans)')
    assert '@import' not in css, f'Unexpected @import left in {source}'
    out = Path('site/src/components/beachmag') / out
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(f'/* Generated by work/build_site_css.py from {source}. Do not edit by hand. */\n' + css.strip() + '\n', encoding='utf-8')
    print(f'{out}: {len(css):,} chars')


site_css('\n'.join(blocks[1:]), 'outputs/coastal-homepage.html', 'beachmag.css')
site_css(Path('work/browser-tabs.css').read_text(encoding='utf-8'), 'work/browser-tabs.css', 'browser-tabs.css')
