"""Trim the empty margin off the client logos for the homepage client strip.

The logos in public/client-icons are white artwork centered in 350x350
transparent squares (3-23% of each is logo), made for the old dark site. The
strip paints them through a CSS mask in the page's ink color, so only the
alpha matters; trimming makes every logo fill its tile the same way.

Run from the repo root: python3 design/work/trim_client_logos.py
Writes public/client-logos/*.webp and src/components/beachmag/client-logos.ts.
"""
from pathlib import Path

from PIL import Image

SOURCE = Path('public/client-icons')
OUT = Path('public/client-logos')
OUT.mkdir(exist_ok=True)
MARGIN = 0.04  # of the trimmed logo's longer side, so strokes don't touch the edge

names = []
for path in sorted(SOURCE.glob('*.webp')):
    image = Image.open(path).convert('RGBA')
    box = image.getchannel('A').point(lambda a: 255 if a > 24 else 0).getbbox()
    if not box:
        continue
    logo = image.crop(box)
    pad = round(max(logo.size) * MARGIN)
    framed = Image.new('RGBA', (logo.width + 2 * pad, logo.height + 2 * pad))
    framed.paste(logo, (pad, pad))
    name = path.name.replace(' ', '-')
    framed.save(OUT / name, 'WEBP', quality=90, method=6)
    names.append((path.name, name, framed.size))
    print(f'{name}: {image.size[0]}x{image.size[1]} -> {framed.size[0]}x{framed.size[1]}')

entries = ',\n'.join(f'  [{orig!r}, {name!r}]' for orig, name, _ in names).replace("'", '"')
Path('src/components/beachmag/client-logos.ts').write_text(
    '// Generated by design/work/trim_client_logos.py. Do not edit by hand.\n'
    '// public/client-icons file name -> trimmed copy in public/client-logos.\n'
    f'export const TRIMMED_LOGOS = new Map<string, string>([\n{entries},\n]);\n',
    encoding='utf-8',
)
